"""Embed images referenced in assets/manifest.js (or manifest.example.js) as data URIs (assets/embedded.js).

Lively loads the wallpaper from file://, where WebGL refuses plain image files.
Run this after adding photos/art:  python tools/embed_assets.py
"""
import base64
import json
import mimetypes
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".webp"}


def main() -> None:
    src = ROOT / "assets" / "manifest.js"
    if not src.is_file():
        src = ROOT / "assets" / "manifest.example.js"
    manifest = src.read_text(encoding="utf-8")
    paths = sorted(set(re.findall(r"['\"](assets/[^'\"]+)['\"]", manifest)))
    embedded = {}
    for rel in paths:
        f = ROOT / rel
        if f.suffix.lower() not in IMAGE_EXT:
            continue
        if not f.is_file():
            print(f"missing: {rel}")
            continue
        mime = mimetypes.guess_type(f.name)[0] or "image/png"
        embedded[rel] = f"data:{mime};base64," + base64.b64encode(f.read_bytes()).decode()
        print(f"embedded: {rel} ({f.stat().st_size // 1024} KB)")
    out = ROOT / "assets" / "embedded.js"
    out.write_text("// Generated by tools/embed_assets.py — do not edit.\nwindow.EMBEDDED = "
                   + json.dumps(embedded) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} with {len(embedded)} image(s)")


if __name__ == "__main__":
    main()
